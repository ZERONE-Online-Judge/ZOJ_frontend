export function searchOperatorGuide(query: string) {
  const words = query
    .trim()
    .toLocaleLowerCase('ko')
    .split(/\s+/)
    .filter(Boolean);
  if (!words.length) return [];
  return operatorGuideCategories.flatMap((category) =>
    category.articles
      .filter((article) => {
        const haystack =
          `${category.label} ${JSON.stringify(article)}`.toLocaleLowerCase(
            'ko',
          );
        return words.every((word) => haystack.includes(word));
      })
      .map((article) => ({ category, article })),
  );
}
